export function loadTokens() {
  return JSON.parse(fs.readFileSync(TOKENS_FILE, 'utf8'));
}

/** Style Dictionary config for the given output directory. */
export function makeConfig({ outDir = path.join(here, 'dist'), silent = false } = {}) {
  const buildPath = (sub) => path.join(outDir, sub) + path.sep;
  const common = ['kesher/name', 'kesher/color/tint'];
  return {
    usesDtcg: true,
    log: { verbosity: silent ? logVerbosityLevels.silent : logVerbosityLevels.default },
    source: [TOKENS_FILE],
    preprocessors: ['kesher/modes'],
    hooks: {
      preprocessors: { 'kesher/modes': (tokens) => expandModes(tokens) },
      transforms,
      formats: {
        'kesher/css': cssFormat,
        'kesher/tailwind': tailwindFormat,
        'kesher/native': nativeFormat,
        'kesher/json/flat': flatJsonFormat,
      },
    },
    platforms: {
      css: {
        transforms: [...common, 'kesher/css/dimension', 'kesher/css/duration', 'kesher/css/cubicBezier', 'kesher/css/fontFamily', 'kesher/css/shadow', 'kesher/css/typography'],
        buildPath: buildPath('css'),
        files: [{ destination: 'tokens.css', format: 'kesher/css' }],
      },
      tailwind: {
        transforms: [...common, 'kesher/css/dimension', 'kesher/css/duration', 'kesher/css/cubicBezier', 'kesher/css/fontFamily', 'kesher/css/shadow', 'kesher/css/typography'],
        buildPath: buildPath('tailwind'),
        files: [{ destination: 'preset.js', format: 'kesher/tailwind' }],
      },
      native: {
        transforms: [...common, 'kesher/native/dimension', 'kesher/native/duration', 'kesher/native/fontFamily', 'kesher/native/shadow', 'kesher/native/typography'],
        buildPath: buildPath('native'),
        files: [{ destination: 'theme.ts', format: 'kesher/native' }],
      },
      json: {
        transforms: common,
        buildPath: buildPath('json'),
        files: [{ destination: 'tokens.flat.json', format: 'kesher/json/flat' }],
      },
    },
  };
}

/**
 * Builds every output. `generatedFile` (default `src/theme.generated.ts`) receives a copy of the
 * native theme so the package typechecks without a build; pass `null` to skip it.
 */
export async function buildTokens({ outDir = path.join(here, 'dist'), generatedFile = path.join(here, 'src', 'theme.generated.ts'), silent = false } = {}) {
  const sd = new StyleDictionary(makeConfig({ outDir, silent }));
  await sd.hasInitialized;
  await sd.buildAllPlatforms();
  const files = {
    css: path.join(outDir, 'css', 'tokens.css'),
    tailwind: path.join(outDir, 'tailwind', 'preset.js'),
    native: path.join(outDir, 'native', 'theme.ts'),
    json: path.join(outDir, 'json', 'tokens.flat.json'),
  };
  if (generatedFile) {
    fs.mkdirSync(path.dirname(generatedFile), { recursive: true });
    fs.copyFileSync(files.native, generatedFile);
  }
  return { outDir, files, generatedFile };
}

export default makeConfig();

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { files, generatedFile } = await buildTokens();
  for (const f of [...Object.values(files), generatedFile]) console.log(`wrote ${path.relative(process.cwd(), f)}`);
}
