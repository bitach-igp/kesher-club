// Style Dictionary 5 build for @kesher/tokens (T-0006).
//
// Source: tokens.json (W3C DTCG). Colour tokens hold their light value in `$value` and their dark
// value in `$extensions['club.kesher.modes'].dark`. The `kesher/modes` preprocessor expands every
// colour token into `light.<path>` and `dark.<path>` (rewriting references so `{color.status.success}`
// resolves per mode), so one dictionary carries both modes and every format can emit both.
//
// Outputs (all generated, never edited by hand):
//   dist/css/tokens.css          CSS variables: `:root` (light), `[data-theme="dark"]`, prefers-color-scheme
//   dist/tailwind/preset.js      Tailwind preset (colors via the CSS vars, spacing, radius, fontSize, shadows)
//   dist/native/theme.ts         Typed React Native theme: `light` and `dark`, numbers for px, no units
//   dist/json/tokens.flat.json   Flat `path -> token` map with light/dark values
//   src/theme.generated.ts       Copy of the native theme, committed so the package typechecks unbuilt
//
// Run: `pnpm --filter @kesher/tokens build` (or `node sd.config.mjs`).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { transformTypes, logVerbosityLevels } from 'style-dictionary/enums';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_FILE = path.join(here, 'tokens.json');
export const MODES = /** @type {const} */ (['light', 'dark']);
const MODES_EXT = 'club.kesher.modes';
const MODE_EXT = 'club.kesher.mode';
const HEADER = 'Generated by packages/tokens/sd.config.mjs from packages/tokens/tokens.json. Do not edit; change the token and rebuild.';

// ---------------------------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------------------------

const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);
const isToken = (node) => isObject(node) && '$value' in node;

/** `moneyHero` -> `money-hero`, `1` -> `1`. */
const kebab = (segment) => segment.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** Path of a token without its mode prefix. */
const unmodedPath = (token) => (MODES.includes(token.path[0]) ? token.path.slice(1) : token.path);
const modeOf = (token) => (MODES.includes(token.path[0]) ? token.path[0] : undefined);

/** `#RRGGBB` or `#RRGGBBAA` -> { r, g, b, a } with a in 0..1. */
export function parseHex(hex) {
  const m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(hex);
  if (!m) throw new Error(`kesher/tokens: expected a #RRGGBB[AA] colour, got ${JSON.stringify(hex)}`);
  const n = parseInt(m[1], 16);
  return { r: n >> 16, g: (n >> 8) & 255, b: n & 255, a: m[2] ? parseInt(m[2], 16) / 255 : 1 };
}

const toHex2 = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase();
export const toHex = ({ r, g, b }) => `#${toHex2(r)}${toHex2(g)}${toHex2(b)}`;

/** Composite `color` over `on` at `alpha` (the "8% tint of the status colour on surface" rule). */
export function tint(color, on, alpha) {
  const c = parseHex(color);
  const o = parseHex(on);
  const mix = (x, y) => y * (1 - alpha) + x * alpha;
  return toHex({ r: mix(c.r, o.r), g: mix(c.g, o.g), b: mix(c.b, o.b) });
}

const dim = (v) => (isObject(v) ? `${v.value}${v.value === 0 ? '' : v.unit}` : v);
const num = (v) => (isObject(v) ? v.value : typeof v === 'string' ? parseFloat(v) : v);
const quoteFamily = (f) => (/^[a-zA-Z-]+$/.test(f) ? f : JSON.stringify(f));

/** Rewrites `{a.b.c}` references inside any value so moded targets point at the given mode. */
function rewriteRefs(value, mode, moded) {
  if (typeof value === 'string') {
    return value.replace(/\{([^}]+)\}/g, (whole, ref) => (moded.has(ref) ? `{${mode}.${ref}}` : whole));
  }
  if (Array.isArray(value)) return value.map((v) => rewriteRefs(v, mode, moded));
  if (isObject(value)) return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, rewriteRefs(v, mode, moded)]));
  return value;
}

function setPath(tree, segments, leaf) {
  let node = tree;
  for (const s of segments.slice(0, -1)) node = node[s] ??= {};
  node[segments[segments.length - 1]] = leaf;
}

// ---------------------------------------------------------------------------------------------
// Preprocessor: expand colour tokens into light.* and dark.*
// ---------------------------------------------------------------------------------------------

/** Collects every leaf token with its inherited `$type`. */
export function collectLeaves(tree, inheritedType, prefix = []) {
  const leaves = [];
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$') || !isObject(node)) continue;
    const type = node.$type ?? inheritedType;
    if (isToken(node)) leaves.push({ path: [...prefix, key], token: { ...node, $type: type } });
    else leaves.push(...collectLeaves(node, type, [...prefix, key]));
  }
  return leaves;
}

/** Pure form of the preprocessor so tests can call it without Style Dictionary. */
export function expandModes(tree) {
  const leaves = collectLeaves(tree);
  const moded = new Set(leaves.filter((l) => l.token.$type === 'color').map((l) => l.path.join('.')));
  const out = {};
  for (const { path: p, token } of leaves) {
    if (!moded.has(p.join('.'))) {
      setPath(out, p, token);
      continue;
    }
    const { [MODES_EXT]: modeValues, ...otherExt } = token.$extensions ?? {};
    for (const mode of MODES) {
      const raw = mode === 'light' ? token.$value : (modeValues?.[mode] ?? token.$value);
      setPath(out, [mode, ...p], {
        ...token,
        $value: rewriteRefs(raw, mode, moded),
        $extensions: { ...otherExt, [MODE_EXT]: mode },
      });
    }
  }
  return out;
}

