// Transforms
// ---------------------------------------------------------------------------------------------

/** CSS custom-property name without the mode prefix: `--color-bg-canvas` for both modes. */
const cssName = (token) => unmodedPath(token).map(kebab).join('-');

const typeIs = (type) => (token) => token.$type === type;

const transforms = {
  // Unique per mode (`light-color-bg-canvas`) so Style Dictionary sees no collisions; formats use cssName().
  'kesher/name': { type: transformTypes.name, transform: (token) => token.path.map(kebab).join('-') },

  // Computes the *Subtle tints from { color, on, alpha } once the references have resolved.
  'kesher/color/tint': {
    type: transformTypes.value,
    transitive: true,
    filter: (token) => token.$type === 'color' && isObject(token.$value) && 'alpha' in token.$value,
    transform: (token) => tint(token.$value.color, token.$value.on, token.$value.alpha),
  },

  // CSS: strings with units.
  'kesher/css/dimension': { type: transformTypes.value, transitive: true, filter: typeIs('dimension'), transform: (t) => dim(t.$value) },
  'kesher/css/duration': { type: transformTypes.value, transitive: true, filter: typeIs('duration'), transform: (t) => dim(t.$value) },
  'kesher/css/cubicBezier': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('cubicBezier'),
    transform: (t) => (Array.isArray(t.$value) ? `cubic-bezier(${t.$value.join(', ')})` : t.$value),
  },
  'kesher/css/fontFamily': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('fontFamily'),
    transform: (t) => (Array.isArray(t.$value) ? t.$value.map(quoteFamily).join(', ') : t.$value),
  },
  'kesher/css/shadow': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('shadow'),
    transform: (t) =>
      Array.isArray(t.$value)
        ? t.$value.map((l) => `${dim(l.offsetX)} ${dim(l.offsetY)} ${dim(l.blur)} ${dim(l.spread)} ${l.color}`).join(', ')
        : t.$value,
  },
  'kesher/css/typography': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('typography'),
    transform: (t) => {
      const v = t.$value;
      if (!isObject(v)) return v;
      const out = {
        fontFamily: Array.isArray(v.fontFamily) ? v.fontFamily.map(quoteFamily).join(', ') : v.fontFamily,
        fontSize: dim(v.fontSize),
        lineHeight: dim(v.lineHeight),
        fontWeight: String(v.fontWeight),
      };
      if (v.letterSpacing !== undefined) out.letterSpacing = dim(v.letterSpacing);
      if (v.textTransform !== undefined) out.textTransform = v.textTransform;
      if (v.fontFeatureSettings !== undefined) out.fontFeatureSettings = JSON.stringify(v.fontFeatureSettings);
      return out;
    },
  },

  // React Native: plain numbers, no units.
  'kesher/native/dimension': { type: transformTypes.value, transitive: true, filter: typeIs('dimension'), transform: (t) => num(t.$value) },
  'kesher/native/duration': { type: transformTypes.value, transitive: true, filter: typeIs('duration'), transform: (t) => num(t.$value) },
  'kesher/native/fontFamily': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('fontFamily'),
    transform: (t) => (Array.isArray(t.$value) ? t.$value[0] : t.$value),
  },
  'kesher/native/shadow': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('shadow'),
    transform: (t) => {
      if (!Array.isArray(t.$value)) return t.$value;
      // iOS takes the first (widest) layer; Android gets the elevation level from the token name.
      const [layer] = t.$value;
      const { a, ...rgb } = parseHex(layer.color);
      return {
        shadowColor: toHex(rgb),
        shadowOpacity: Math.round(a * 100) / 100,
        shadowOffset: { width: num(layer.offsetX), height: num(layer.offsetY) },
        shadowRadius: num(layer.blur) / 2,
        elevation: Number(t.path[t.path.length - 1]) || 1,
      };
    },
  },
  'kesher/native/typography': {
    type: transformTypes.value,
    transitive: true,
    filter: typeIs('typography'),
    transform: (t) => {
      const v = t.$value;
      if (!isObject(v) || typeof v.fontSize === 'number') return v;
      const fontSize = num(v.fontSize);
      const out = {
        fontFamily: Array.isArray(v.fontFamily) ? v.fontFamily[0] : v.fontFamily,
        fontSize,
        lineHeight: num(v.lineHeight),
        fontWeight: String(v.fontWeight),
      };
      if (v.letterSpacing !== undefined) {
        const ls = v.letterSpacing;
        out.letterSpacing = isObject(ls) && ls.unit === 'em' ? Math.round(ls.value * fontSize * 100) / 100 : num(ls);
      }
      if (v.textTransform !== undefined) out.textTransform = v.textTransform;
      if (v.fontFeatureSettings === 'tnum') out.fontVariant = ['tabular-nums'];
      return out;
    },
  },
};

// ---------------------------------------------------------------------------------------------
// Formats
// ---------------------------------------------------------------------------------------------

const byMode = (allTokens) => ({
  shared: allTokens.filter((t) => modeOf(t) === undefined),
  light: allTokens.filter((t) => modeOf(t) === 'light'),
  dark: allTokens.filter((t) => modeOf(t) === 'dark'),
});

/** One token -> one or more `--name: value` CSS declarations (typography expands per property). */
function cssDeclarations(token) {
  if (isObject(token.$value)) {
    return Object.entries(token.$value).map(([prop, v]) => `  --${cssName(token)}-${kebab(prop)}: ${v};`);
  }
  return [`  --${cssName(token)}: ${token.$value};`];
}

function cssFormat({ dictionary }) {
  const { shared, light, dark } = byMode(dictionary.allTokens);
  const block = (tokens) => tokens.flatMap(cssDeclarations).join('\n');
  const darkBlock = block(dark);
  return [
    `/* ${HEADER} */`,
    '',
    '/* Light (default) and every mode-independent token */',
    ':root {',
    block(light),
    '',
    block(shared),
    '}',
    '',
    '/* Dark: manual override in Settings */',
    '[data-theme="dark"] {',
    darkBlock,
    '}',
    '',
    '/* Dark: follows the system setting unless the override says light */',
    '@media (prefers-color-scheme: dark) {',
    '  :root:not([data-theme="light"]) {',
    darkBlock.replace(/^/gm, '  '),
    '  }',
    '}',
    '',
  ].join('\n');
}

/** Serialises a plain value as a JS/TS literal with bare identifier keys. */
function literal(value, indent = '') {
  if (Array.isArray(value)) return `[${value.map((v) => literal(v, indent)).join(', ')}]`;
  if (isObject(value)) {
    const inner = indent + '  ';
    const entries = Object.entries(value).map(([k, v]) => {
      const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
      return `${inner}${key}: ${literal(v, inner)},`;
    });
    return entries.length ? `{\n${entries.join('\n')}\n${indent}}` : '{}';
  }
  return JSON.stringify(value);
}

/** Nested object from tokens, keyed by the unmoded path. */
function nest(tokens) {
  const tree = {};
  for (const t of tokens) setPath(tree, unmodedPath(t), t.$value);
  return tree;
}

function tailwindFormat({ dictionary }) {
  const { shared, light } = byMode(dictionary.allTokens);
  const pick = (root) => nest(shared.filter((t) => t.path[0] === root))[root] ?? {};
  // Colours reference the CSS variables so `[data-theme="dark"]` / prefers-color-scheme switch them.
  const colors = nest(light.filter((t) => t.path[1] === 'color').map((t) => ({ ...t, $value: `var(--${cssName(t)})` }))).color;
  const typography = pick('typography');
  const fontSize = Object.fromEntries(
    Object.entries(typography).map(([k, v]) => {
      // Tailwind's fontSize tuple understands only these three; tnum / uppercase stay on the CSS variables.
      const { fontSize: size, lineHeight, fontWeight, letterSpacing } = v;
      return [kebab(k), [size, { lineHeight, fontWeight, ...(letterSpacing ? { letterSpacing } : {}) }]];
    }),
  );
  const fontFamily = Object.fromEntries(Object.entries(pick('font').family).map(([k, v]) => [k, v.split(', ')]));
  const boxShadow = Object.fromEntries(Object.entries(pick('elev')).map(([k, v]) => [`elev-${k}`, v]));
  const motion = pick('motion');
  const preset = {
    darkMode: ['selector', '[data-theme="dark"]'],
    theme: {
      extend: {
        colors,
        spacing: pick('space'),
        borderRadius: pick('radius'),
        borderWidth: pick('borderWidth'),
        fontSize,
        fontFamily,
        fontWeight: pick('font').weight,
        boxShadow,
        transitionDuration: motion.duration,
        transitionTimingFunction: motion.easing,
      },
    },
  };
  return `// ${HEADER}\n// Tailwind preset: \`presets: [preset]\` in tailwind.config. Pair it with dist/css/tokens.css.\nconst preset = ${literal(preset)};\n\nexport default preset;\n`;
}

function nativeFormat({ dictionary }) {
  const { shared, light, dark } = byMode(dictionary.allTokens);
  const theme = (modeTokens) => nest([...modeTokens, ...shared]);
  return [
    `// ${HEADER}`,
    '// React Native theme. Numbers are density-independent px; durations are ms.',
    '',
    `const lightTheme = ${literal(theme(light))};`,
    '',
    '/** Shape shared by both modes: colour values differ, everything else is identical. */',
    'export type Theme = typeof lightTheme;',
    '',
    'export const light: Theme = lightTheme;',
    '',
    `export const dark: Theme = ${literal(theme(dark))};`,
    '',
    'export const theme = { light, dark } as const;',
    '',
    'export type ThemeMode = keyof typeof theme;',
    '',
  ].join('\n');
}

function flatJsonFormat({ dictionary }) {
  const { shared, light, dark } = byMode(dictionary.allTokens);
  const out = {};
  const entry = (t) => ({ $type: t.$type, ...(t.$description ? { $description: t.$description } : {}) });
  for (const t of shared) out[t.path.join('.')] = { ...entry(t), $value: t.$value };
  for (const t of light) out[unmodedPath(t).join('.')] = { ...entry(t), $value: { light: t.$value } };
  for (const t of dark) out[unmodedPath(t).join('.')].$value.dark = t.$value;
  return JSON.stringify(out, null, 2) + '\n';
}

// ---------------------------------------------------------------------------------------------
// Config and build
