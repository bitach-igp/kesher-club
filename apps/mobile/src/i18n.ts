const maps: Record<Locale, Record<CopyKey, string>> = { en, he };

/** Looks up a copy key and fills `{name}` placeholders. Values are inserted as text, never interpreted. */
export function t(key: CopyKey, locale: Locale, vars: Record<string, string | number> = {}): string {
  const raw = maps[locale][key];
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export const isRtl = (locale: Locale): boolean => locale === 'he';

